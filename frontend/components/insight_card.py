"""Insight card component: renders rule-based Insight objects from AnalysisResult.insights.

Every insight was already generated by the backend's deterministic
``InsightEngine`` — this component only lays the text out, it never
derives a new fact from the data.
"""

from typing import Any

import streamlit as st


def render_insight_cards(insights: list[dict[str, Any]]) -> None:
    """Render a list of Insight dicts, most-relevant first, as an ordered list of cards."""
    if not insights:
        st.info("No insights were generated for this dataset.")
        return

    for insight in insights:
        with st.container(border=True):
            category = str(insight.get("category", "Insight")).replace("_", " ").title()
            st.markdown(f"**{category}** — {insight.get('message', '')}")
            if insight.get("metric") is not None and insight.get("value") is not None:
                st.caption(f"{insight['metric']}: {insight['value']}")
