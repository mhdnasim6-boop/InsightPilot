"""Reporting providers: builder, validator, theme registry, store, exporters, report service."""

from functools import lru_cache

from fastapi import Depends

from backend.dependencies.memory import get_memory_service
from backend.memory.services.memory_service import MemoryService
from backend.reporting.builders.report_builder import ReportBuilder
from backend.reporting.exporters.json_exporter import JSONReportExporter
from backend.reporting.exporters.markdown_exporter import MarkdownReportExporter
from backend.reporting.exporters.placeholders import (
    PDFReportExporter,
    PowerPointReportExporter,
    WordReportExporter,
)
from backend.reporting.report_store import ReportStore
from backend.reporting.themes.registry import ReportThemeRegistry
from backend.reporting.validation.validator import ReportValidator
from backend.services.report_service import ReportService


@lru_cache
def get_report_builder() -> ReportBuilder:
    """Return the process-wide ReportBuilder singleton (stateless, safe to share)."""
    return ReportBuilder()


@lru_cache
def get_report_validator() -> ReportValidator:
    """Return the process-wide ReportValidator singleton (stateless, safe to share)."""
    return ReportValidator()


@lru_cache
def get_report_theme_registry() -> ReportThemeRegistry:
    """Return the process-wide ReportThemeRegistry singleton (stateless, safe to share)."""
    return ReportThemeRegistry()


@lru_cache
def get_report_store() -> ReportStore:
    """Return the process-wide ReportStore singleton.

    Cached for the same reason as ``get_business_dataset_store``: a report
    generated by one request must still be fetchable/exportable in a
    later one.
    """
    return ReportStore()


@lru_cache
def get_json_report_exporter() -> JSONReportExporter:
    """Return the process-wide JSONReportExporter singleton (stateless, safe to share)."""
    return JSONReportExporter()


@lru_cache
def get_markdown_report_exporter() -> MarkdownReportExporter:
    """Return the process-wide MarkdownReportExporter singleton (stateless, safe to share)."""
    return MarkdownReportExporter()


@lru_cache
def get_pdf_report_exporter() -> PDFReportExporter:
    """Return the process-wide PDFReportExporter singleton (stateless, safe to share)."""
    return PDFReportExporter()


@lru_cache
def get_word_report_exporter() -> WordReportExporter:
    """Return the process-wide WordReportExporter singleton (stateless, safe to share)."""
    return WordReportExporter()


@lru_cache
def get_powerpoint_report_exporter() -> PowerPointReportExporter:
    """Return the process-wide PowerPointReportExporter singleton (stateless, safe to share)."""
    return PowerPointReportExporter()


def get_report_service(
    builder: ReportBuilder = Depends(get_report_builder),
    validator: ReportValidator = Depends(get_report_validator),
    report_store: ReportStore = Depends(get_report_store),
    json_exporter: JSONReportExporter = Depends(get_json_report_exporter),
    markdown_exporter: MarkdownReportExporter = Depends(get_markdown_report_exporter),
    pdf_exporter: PDFReportExporter = Depends(get_pdf_report_exporter),
    word_exporter: WordReportExporter = Depends(get_word_report_exporter),
    powerpoint_exporter: PowerPointReportExporter = Depends(get_powerpoint_report_exporter),
    memory_service: MemoryService = Depends(get_memory_service),
) -> ReportService:
    """Provide the ReportService — the only object that should be used to build, fetch, or export reports."""
    return ReportService(
        builder,
        validator,
        report_store,
        json_exporter,
        markdown_exporter,
        pdf_exporter,
        word_exporter,
        powerpoint_exporter,
        memory_service,
    )
